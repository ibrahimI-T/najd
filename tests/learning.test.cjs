const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { createLearning } = require('../electron/learning.cjs')
const request = { text: 'I prefer concise answers.', provider: 'ollama', modelName: 'fixture' }
async function fixture(t) {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'najd-learning-test-'))
  // Any accidental paid/model extraction is a test failure.
  const learning = createLearning({ directory, chat: () => { throw new Error('Unexpected model request') } })
  t.after(async () => { await learning.cancel(); assert.match(path.basename(directory), /^najd-learning-test-/); await fs.rm(directory, { recursive: true, force: true }) })
  return { directory, learning }
}
test('local learning is on by default (owner directive 2026-10-17), can be switched off, makes zero model calls and stores literal owner words', async t => {
  const { learning } = await fixture(t)
  assert.deepEqual(await learning.settings(), { mode: 'preferences', sharePreferences: true, shareExperiences: true })
  await learning.setSettings({ mode: 'off', sharePreferences: false })
  await learning.review(request)
  assert.equal((await learning.list()).pending.preference.length, 0)
  await learning.setSettings({ mode: 'review', sharePreferences: false })
  await learning.review(request)
  const state = await learning.list()
  assert.equal(state.state, 'idle'); assert.equal(state.pending.preference.length, 1)
  assert.equal(state.pending.preference[0].text, request.text)
  assert.equal(state.approved.preference.length, 0); assert.equal(await learning.context(), undefined)
})
test('approval, correction, deletion and restart persist without duplicate lessons', async t => {
  const { learning, directory } = await fixture(t)
  await learning.setSettings({ mode: 'review', sharePreferences: true })
  await learning.review(request)
  const candidate = (await learning.list()).pending.preference[0]
  await learning.accept('preference', candidate.id)
  await learning.review(request)
  assert.equal((await learning.list()).pending.preference.length, 0)
  assert.match(await learning.context(), /I prefer concise answers/)
  await learning.edit('preference', { id: (await learning.list()).approved.preference[0].id, title: 'Reply style', text: 'I prefer balanced answers.' })
  const reopened = createLearning({ directory })
  assert.match(await reopened.context(), /I prefer balanced answers/)
  await reopened.remove('preference', (await reopened.list()).approved.preference[0].id)
  assert.equal(await reopened.context(), undefined)
})
test('explicit preferences auto-save; corrections, identity and workflow lessons require review', async t => {
  const { learning } = await fixture(t)
  await learning.setSettings({ mode: 'preferences', sharePreferences: true })
  for (const text of [request.text, 'Correction: I prefer detailed replies.', 'My name is Ibrahim.', 'Workflow lesson: verify results.']) await learning.review({ ...request, text })
  const state = await learning.list()
  assert.equal(state.approved.preference[0].text, request.text)
  assert.equal(state.pending.preference.length, 2); assert.equal(state.pending.experience.length, 1)
  assert.equal(state.approved.experience.length, 0)
  assert.equal((await learning.context()).includes('verify results'), false)
})
