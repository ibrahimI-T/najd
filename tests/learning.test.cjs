test('legacy sharing policy never opts into lessons, and Arabic lesson retrieval is bounded', async t => {
  const { directory, learning } = await fixture(t)
  await fs.writeFile(path.join(directory, 'learning-policy.json'), JSON.stringify({ version: 1, settings: { mode: 'review', sharePreferences: true } }))
  assert.equal((await learning.settings()).shareExperiences, false)
  assert.equal(JSON.parse(await fs.readFile(path.join(directory, 'learning-policy.json'), 'utf8')).version, 1, 'Reading legacy policy must not rewrite it')
  const text = 'درس العمل: تحقق من نتائج البناء قبل إعلان النجاح.'
  await learning.review({ ...request, text })
  await learning.accept('experience', (await learning.list()).pending.experience[0].id)
  assert.equal(Boolean((await learning.context('راجع نتائج البناء'))?.includes(text)), false)
  await learning.setSettings({ mode: 'review', sharePreferences: true, shareExperiences: true })
  assert.equal(JSON.parse(await fs.readFile(path.join(directory, 'learning-policy.json'), 'utf8')).version, 2)
  assert.match(await learning.context('راجع نتائج البناء'), /نتائج البناء/)
  assert.ok((await learning.context('راجع نتائج البناء')).length < 1600)
  assert.equal(await learning.context('a'.repeat(4001)), undefined)
  assert.equal(await learning.context('api_key=sk-private-fixture-secret'), undefined)
})

test('future policies and interrupted temporary writes are preserved without clearing approved memories', async t => {
  const { directory, learning } = await fixture(t)
  await learning.setSettings({ mode: 'preferences', sharePreferences: true })
  await learning.review(request)
  const filename = path.join(directory, 'learning-policy.json')
  const original = await fs.readFile(filename, 'utf8')
  await fs.writeFile(filename + '.interrupted.tmp', '{unfinished')
  assert.equal((await learning.list()).approved.preference.length, 1)
  assert.equal(await fs.readFile(filename, 'utf8'), original)
  const future = original.replace('"version":2', '"version":3')
  await fs.writeFile(filename, future)
  await assert.rejects(learning.settings(), { code: 'MEMORY_STORE_UNAVAILABLE' })
  await assert.rejects(learning.setSettings({ mode: 'off', sharePreferences: false }), { code: 'MEMORY_STORE_UNAVAILABLE' })
  assert.equal(await fs.readFile(filename, 'utf8'), future)
  assert.equal(JSON.parse(await learning.exportKind('preference')).notes.length, 1)
})

test('model-initiated memory follows the learning mode, refuses secrets and can be forgotten', async t => {
  const { learning } = await fixture(t)
  const saved = await learning.remember({ kind: 'preference', text: 'Prefers short answers with a summary first.' })
  assert.equal(saved.status, 'saved')
  assert.equal((await learning.remember({ kind: 'preference', text: 'Prefers short answers with a summary first.' })).status, 'already_known')
  await assert.rejects(learning.remember({ kind: 'preference', text: 'api_key: sk-abcdef1234567890' }), { code: 'MEMORY_REFUSED' })
  assert.match(await learning.context('answers'), /Prefers short answers/)
  await learning.forget({ kind: 'preference', id: saved.id })
  assert.equal(await learning.context('answers'), undefined)
  await learning.setSettings({ mode: 'review', sharePreferences: true })
  assert.equal((await learning.remember({ kind: 'experience', text: 'Run the desktop smoke after UI changes.' })).status, 'saved_for_review')
  await learning.setSettings({ mode: 'off', sharePreferences: false })
  await assert.rejects(learning.remember({ kind: 'preference', text: 'Likes tables.' }), { code: 'MEMORY_DISABLED' })
})
