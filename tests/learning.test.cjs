test('backup restores facts without enabling learning or sharing and experiences remain isolated', async t => {
  const source = (await fixture(t)).learning, target = (await fixture(t)).learning
  await source.setSettings({ mode: 'preferences', sharePreferences: true }); await source.review(request)
  const backup = await source.exportKind('preference')
  await target.setSettings({ mode: 'off', sharePreferences: false })
  const before = await target.settings()
  await target.importKind('preference', backup)
  assert.equal((await target.list()).approved.preference.length, 1)
  assert.deepEqual(await target.settings(), before, 'importing a backup never changes learning settings')
  assert.equal(await target.context(), undefined)
  await target.importKind('experience', backup)
  await target.setSettings({ mode: 'off', sharePreferences: true })
  await target.remove('preference', (await target.list()).approved.preference[0].id)
  assert.equal(await target.context(), undefined)
})
