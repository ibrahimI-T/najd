// MCP failure classification and readiness: real error codes survive, permanent failures are not repeated, a
// connected server is not reported ready for a tool that already proved impossible.
const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { classifyFailure, createHealthBook, readiness } = require('../electron/mcp-health.cjs')
const { createMcpServers } = require('../electron/mcp-servers.cjs')

test('the failures seen in the REA report are classified by their real cause', () => {
  const a = classifyFailure({ text: JSON.stringify({ status: 'unsupported_provider', message: 'pwntools-elf supports Linux x64 only' }) })
  assert.equal(a.code, 'UNSUPPORTED_PROVIDER'); assert.equal(a.class, 'unsupported'); assert.equal(a.permanent, true)
  const b = classifyFailure({ text: 'capability_unavailable ERR_REA_WINDOWS_NATIVE' })
  assert.equal(b.class, 'unsupported'); assert.equal(b.permanent, true)
  const c = classifyFailure({ text: 'target_unavailable: No app is open' })
  assert.equal(c.class, 'target_unavailable'); assert.equal(c.permanent, false)
  const d = classifyFailure({ text: 'SENSITIVE_FILE' })
  assert.equal(d.class, 'permission')
  assert.equal(classifyFailure({ code: 'TIMEOUT' }).class, 'timeout')
  assert.equal(classifyFailure({ code: 'SERVER_EXITED', detail: 'exit 1' }).class, 'server_exited')
  assert.equal(classifyFailure({ text: 'something odd' }).class, 'app_error')
})

test('readiness separates installed, connected, compatible, configured and tested', () => {
  const book = createHealthBook()
  assert.equal(readiness({ installed: true, connected: true, row: book.get('s', 't') }).ready, true)
  book.recordFailure('s', 't', classifyFailure({ text: 'unsupported_provider' }), 12)
  const r = readiness({ installed: true, connected: true, row: book.get('s', 't') })
  assert.equal(r.ready, false); assert.equal(r.platformCompatible, false); assert.equal(r.reason, 'UNSUPPORTED_PROVIDER'); assert.equal(r.connected, true)
  book.clearServer('s'); assert.equal(book.blocked('s', 't'), null)
})

test('a live server: an unsupported tool is recorded once, the working tool stays ready', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'najd-mcp-health-'))
  const server = path.join(dir, 'server.cjs')
  fs.writeFileSync(server, `
const rl = require('node:readline').createInterface({ input: process.stdin })
const send = m => process.stdout.write(JSON.stringify({ jsonrpc: '2.0', ...m }) + String.fromCharCode(10))
rl.on('line', line => { const m = JSON.parse(line)
  if (m.method === 'initialize') return send({ id: m.id, result: { protocolVersion: '2025-06-18', capabilities: { tools: {} }, serverInfo: { name: 'fake', version: '1' } } })
  if (m.method === 'tools/list') return send({ id: m.id, result: { tools: [{ name: 'good', inputSchema: { type: 'object' } }, { name: 'bad', inputSchema: { type: 'object' } }] } })
  if (m.method === 'tools/call') return m.params.name === 'good' ? send({ id: m.id, result: { content: [{ type: 'text', text: 'ok' }] } })
    : send({ id: m.id, result: { isError: true, content: [{ type: 'text', text: '{"status":"unsupported_provider"}' }] } }) })
`)
  const servers = createMcpServers({ filePath: path.join(dir, 'mcp.json'), clientVersion: 't', confirm: async () => true, getBundledNode: () => process.execPath })
  const added = await servers.add({ name: 'Fake', command: 'najd-node', args: [server] }, { approvedInChat: true })
  const view = await servers.connect(added.server.id)
  assert.equal(view.state, 'connected', String(view.error)); assert.equal(view.tools.every(t => t.readiness.ready), true)
  const bad = await servers.call(added.server.id, 'bad', {})
  assert.equal(bad.isError, true); assert.equal(bad.failure.code, 'UNSUPPORTED_PROVIDER')
  const good = await servers.call(added.server.id, 'good', {})
  assert.equal(good.isError, false); assert.ok(good.durationMs >= 0)
  const tools = await servers.tools()
  assert.equal(tools.find(t => t.name === 'bad').readiness.ready, false)
  assert.equal(tools.find(t => t.name === 'good').readiness.lastFunctionalTest.ok, true)
  assert.ok(servers.health.blocked(added.server.id, 'bad'))
  servers.stopAll()
})
