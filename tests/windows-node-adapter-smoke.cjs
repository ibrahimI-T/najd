const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { randomUUID } = require('node:crypto')
const { createWindowsNode } = require('../electron/windows-node.cjs')
const { createOpenClawGateway } = require('../electron/openclaw-gateway.cjs')
async function main() {
  const stateRoot = await fs.mkdtemp(path.join(os.tmpdir(), 'najd-node-adapter-'))
  const node = createWindowsNode({ runtimeRoot: path.resolve(__dirname, '../.runtimes'), stateRoot })
  const gateway = createOpenClawGateway({ runtimeRoot: path.resolve(__dirname, '../.runtimes'), stateRoot: path.join(stateRoot, 'gateway') })
  const paired = createWindowsNode({ runtimeRoot: path.resolve(__dirname, '../.runtimes'), stateRoot: path.join(stateRoot, 'paired-node'),
    nodeConnection: operation => gateway.withLocalNodeConnection(operation) })
  try {
    const connection = await node.connect()
    assert.equal(connection.protocolVersion, '2024-11-05')
    assert.deepEqual(connection.tools, ['system.which', 'najd.windows.demo'])
    assert.equal(typeof connection.serverInfo.name, 'string')
    const [first, shared] = await Promise.all([node.discoverApps(), node.discoverApps()])
    assert.deepEqual(first, shared)
    assert.deepEqual(first.map(item => item.id), ['notepad', 'calc', 'mspaint', 'chrome', 'edge'])
    assert.equal(first.find(item => item.id === 'notepad').found, true)
    assert.equal(first.find(item => item.id === 'calc').found, true)
    assert.equal(first.find(item => item.id === 'chrome').found, true)
    assert.equal(first.find(item => item.id === 'edge').found, true)
    assert.equal(JSON.stringify(first).includes('token'), false)
    assert.equal(JSON.stringify(first).includes('C:'), false)
    await node.stop()
    assert.deepEqual(await node.connect(), connection)
    assert.deepEqual(await node.discoverApps(), first)
    await node.stop()
    const missing = createWindowsNode({ runtimeRoot: path.join(stateRoot, 'missing'), stateRoot: path.join(stateRoot, 'unused') })
    await assert.rejects(missing.discoverApps(), { code: 'WINDOWS_NODE_NOT_INSTALLED' })
    await missing.stop()
    await gateway.start()
    assert.deepEqual(await paired.discoverApps(), first)
    const receipt = paired.pairingReceipt()
    assert.match(receipt.nodeId, /^[a-f0-9]{64}$/i)
    assert.ok(Date.parse(receipt.verifiedAt))
    await gateway.withLocalNodeConnection(async connection => {
      await assert.rejects(connection.approvePairing({ nodeId: 'invalid', requestId: randomUUID() }), { code: 'INVALID_INPUT' })
      await assert.rejects(connection.approvePairing({ nodeId: receipt.nodeId, requestId: randomUUID() }), { code: 'PAIRING_REQUEST_NOT_FOUND' })
    })
    await paired.stop()
    assert.equal(paired.pairingReceipt(), null)
    assert.deepEqual(await paired.discoverApps(), first)
    assert.equal(paired.pairingReceipt().nodeId, receipt.nodeId)
    await paired.stop()
    await gateway.stop()
    console.log('PASS: native adapter private stdio discovery, scoped results, shared calls, shutdown/restart and missing payload refusal.')
  } finally {
    await node.stop()
    await paired.stop()
    await gateway.stop()
    if (!path.resolve(stateRoot).startsWith(path.resolve(os.tmpdir()) + path.sep)) throw new Error('Unsafe fixture path')
    await fs.rm(stateRoot, { recursive: true, force: true })
  }
}
main().catch(error => { console.error(error.message, error.diagnostic || ''); process.exitCode = 1 })
