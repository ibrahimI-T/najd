const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const { createSkillPacks } = require('../electron/skill-packs.cjs')
const { createInstructionSkills } = require('../electron/instruction-skills.cjs')
const root = path.join(__dirname, '../skill-packs')
const temp = t => { const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'najd-packs-')); t.after(() => fs.rmSync(dir, { recursive: true, force: true })); return dir }

test('the vendored skill packs match their pinned manifest byte for byte', () => {
  const out = execFileSync(process.execPath, [path.join(__dirname, '../scripts/vendor-skill-packs.cjs'), '--check'], { encoding: 'utf8' })
  assert.match(out, /Verified \d+ files in 5 pinned skill packs/)
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'))
  assert.deepEqual(manifest.packs.map(pack => [pack.id, pack.license]).sort(), [['designlang', 'MIT'], ['gsap', 'MIT'], ['impeccable', 'Apache-2.0'], ['playwright', 'Apache-2.0'], ['taste', 'MIT']])
  for (const pack of manifest.packs) assert.ok(pack.files.some(file => file.path === 'LICENSE'), pack.id + ' keeps its license')
  assert.ok(manifest.packs.find(pack => pack.id === 'impeccable').files.some(file => file.path === 'NOTICE.md'), 'Apache NOTICE kept')
})

test('every pack guide becomes an enabled instruction skill with its folder and files', async t => {
  const packs = createSkillPacks({ root })
  const ids = packs.rows().map(row => row.id).sort()
  assert.deepEqual(ids, ['pack-designlang-extract-design', 'pack-gsap-gsap-core', 'pack-gsap-gsap-frameworks', 'pack-gsap-gsap-performance', 'pack-gsap-gsap-plugins',
    'pack-gsap-gsap-react', 'pack-gsap-gsap-scrolltrigger', 'pack-gsap-gsap-timeline', 'pack-gsap-gsap-utils', 'pack-impeccable-impeccable', 'pack-playwright-playwright-cli', 'pack-taste-design-taste-frontend'])
  assert.match(packs.rows().find(row => row.id === 'pack-taste-design-taste-frontend').description, /anti-slop frontend skill/)
  const skills = createInstructionSkills({ filePath: path.join(temp(t), 'instruction-skills.json'), bundle: { version: 1, skills: packs.rows(), notices: [] } })
  assert.ok((await skills.list()).every(row => row.enabled && row.source === 'pack'))
  const guide = await skills.read('pack-impeccable-impeccable', 0, 8000)
  assert.match(guide.text, /^---\nname: impeccable/)
  const described = packs.describe('pack-impeccable-impeccable')
  assert.equal(described.folder, path.join(root, 'impeccable', 'impeccable'))
  assert.ok(described.files.includes('reference/typeset.md') && described.files.includes('scripts/impeccable.cmd') && !described.files.includes('SKILL.md'))
  const page = await packs.readFile('pack-impeccable-impeccable', 'reference/typeset.md', 0, 6000)
  assert.ok(page.text.length > 100 && page.characters >= page.text.length)
})

test('pack files are read only when listed and unchanged', async t => {
  const packs = createSkillPacks({ root })
  for (const file of ['../LICENSE', 'SKILL.md', '/etc/passwd', 'reference/../SKILL.md', 'reference\\typeset.md', 'missing.md'])
    await assert.rejects(packs.readFile('pack-impeccable-impeccable', file, 0, 100), { code: 'NOT_FOUND' }, file)
  await assert.rejects(packs.readFile('pack-unknown', 'reference/typeset.md', 0, 100), { code: 'NOT_FOUND' })
  const copy = temp(t)
  fs.cpSync(root, copy, { recursive: true })
  fs.appendFileSync(path.join(copy, 'impeccable/impeccable/reference/typeset.md'), 'changed')
  await assert.rejects(createSkillPacks({ root: copy }).readFile('pack-impeccable-impeccable', 'reference/typeset.md', 0, 100), { code: 'INTEGRITY_FAILED' })
  fs.appendFileSync(path.join(copy, 'gsap/gsap-core/SKILL.md'), 'changed')
  assert.throws(() => createSkillPacks({ root: copy }), { code: 'INTEGRITY_FAILED' })
  assert.deepEqual(createSkillPacks({ root: path.join(copy, 'absent') }).rows(), [])
})

test('the web builder guide names exactly the shipped pack skills, and they ship and are credited', () => {
  const guide = fs.readFileSync(path.join(__dirname, '../electron/najd-skills/najd-web-builder.md'), 'utf8')
  const named = [...new Set(guide.match(/pack-[a-z0-9-]+/g))].sort()
  assert.deepEqual(named, createSkillPacks({ root }).rows().map(row => row.id).sort())
  assert.match(guide, /reactbits\.dev\/r\/<Name>-TS-TW/)
  assert.match(guide, /transitions\.dev\/[a-f0-9]{40}\/skills\/transitions-dev\/SKILL\.md/)
  const pkg = require('../package.json')
  assert.ok(pkg.build.extraResources.some(row => row.from === 'skill-packs' && row.to === 'skill-packs'))
  const notices = createSkillPacks({ root }).notices().join('\n')
  for (const title of ['Taste Skill', 'Impeccable', 'GSAP Skills', 'Playwright CLI', 'Designlang']) assert.ok(notices.includes(title), title)
  assert.match(fs.readFileSync(path.join(__dirname, '../scripts/generate-notices.cjs'), 'utf8'), /skill-packs\.cjs'\)\.createSkillPacks\(/)
  assert.match(fs.readFileSync(path.join(__dirname, '../.gitattributes'), 'utf8'), /^skill-packs\/\*\* -text\r?$/m)
})

test('the model reads pack files through najd_skills_read and main routes them only for pack skills', () => {
  const runtime = fs.readFileSync(path.join(__dirname, '../electron/agent-runtime.cjs'), 'utf8')
  assert.match(runtime, /\['najd_skills_read', 'skills\.read', [^\]]*\{ id: \{ type: 'string' \}, file: \{ type: 'string' \}/)
  assert.match(runtime, /typeof args\.file === 'string' && args\.file \? args\.file\.slice\(0, 300\) : undefined\); break/)
  const main = fs.readFileSync(path.join(__dirname, '../electron/main.cjs'), 'utf8')
  assert.match(main, /createSkillSurface\(\{ bundled: bundledSkills, external: externalSkills, packs: skillPacks \}\)/)
})

test('after an upgrade, a settings file saved before the packs existed still has every pack on, and they cannot be turned off (C85-01)', async t => {
  const packs = createSkillPacks({ root })
  const filePath = path.join(temp(t), 'instruction-skills.json')
  fs.writeFileSync(filePath, JSON.stringify({ version: 1, enabled: { 'hermes-example-12345678': 'a'.repeat(64) } }))
  const skills = createInstructionSkills({ filePath, bundle: { version: 1, skills: packs.rows(), notices: [] } })
  const listed = await skills.list()
  assert.equal(listed.length, packs.rows().length)
  assert.ok(listed.every(row => row.enabled && row.builtIn))
  assert.match((await skills.read('pack-gsap-gsap-core', 0, 6000)).text, /name: gsap-core/)
  await assert.rejects(skills.setEnabled('pack-gsap-gsap-core', false), { code: 'BUILT_IN_GUIDE' })
})
