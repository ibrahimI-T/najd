const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { createLegalNotices } = require('../electron/legal-notices.cjs')

test('packaged legal reader uses fixed shipped files and does not inspect source/user data', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'najd-notices-'))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  await fs.writeFile(path.join(root, 'THIRD-PARTY-NOTICES.txt'), 'Renderer license fixture')
  await fs.writeFile(path.join(root, 'LICENSE.electron.txt'), 'Electron license fixture')
  const read = createLegalNotices({ appRoot: path.join(root, 'no-source'), resourcesRoot: root, electronRoot: root, packaged: true })
  const text = await read('../../private.txt')
  assert.ok(text.includes('Renderer license fixture'))
  assert.ok(text.includes('Electron license fixture'))
  assert.ok(text.includes('LICENSES.chromium.html'))
  // A notices list of several hundred KB (the bundled one with Mermaid is about 425 KB) is read; past 1 MB a file is refused.
  await fs.writeFile(path.join(root, 'THIRD-PARTY-NOTICES.txt'), 'n'.repeat(600 * 1024))
  assert.ok((await read()).length > 600 * 1024)
  await fs.writeFile(path.join(root, 'LICENSE.electron.txt'), 'x'.repeat(1024 * 1024 + 1))
  await assert.rejects(read(), { code: 'LEGAL_NOTICES_UNAVAILABLE' })
  await fs.rm(path.join(root, 'LICENSE.electron.txt'))
  await assert.rejects(read(), { code: 'LEGAL_NOTICES_UNAVAILABLE' })
})
