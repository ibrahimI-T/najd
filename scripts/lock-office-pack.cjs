// Developer tool (docs/AGENT-PLATFORM-M3-PLAN.md, M3-1): writes electron/packs/office-pack.lock.txt, the pinned,
// hash-verified Office and design pack. Resolves the full dependency closure with the managed engine's own uv for the
// engine's base interpreter (which najd_python_run uses with -I and which sees none of the engine venv's packages,
// M3-008), and keeps for each package only the SHA-256 hashes of wheels that can install on it (cp314 win_amd64, abi3
// win_amd64 or pure Python), read from PyPI's JSON API.
// The lock is committed and reviewed like code; the app trusts only these hashes.
// Usage: node scripts/lock-office-pack.cjs [--engine <engine folder>] [--check]
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const { createHash } = require('node:crypto')

const REQUESTED = ['python-docx', 'openpyxl', 'python-pptx', 'XlsxWriter', 'matplotlib']
const IMPORTS = ['docx', 'openpyxl', 'pptx', 'xlsxwriter', 'matplotlib', 'numpy', 'lxml', 'PIL']
const LOCK = path.join(__dirname, '..', 'electron', 'packs', 'office-pack.lock.txt')
const normal = name => name.toLowerCase().replace(/[-_.]+/g, '-')
// Wheel tags the engine (CPython 3.14, Windows x64) can install.
const installable = filename => /-(py3|py2\.py3)-none-any\.whl$/.test(filename) || /-cp314-cp314-win_amd64\.whl$/.test(filename) ||
  /-cp3(?:[2-9]|1[0-4])-abi3-win_amd64\.whl$/.test(filename)

function findEngine(argument) {
  if (argument) return path.resolve(argument)
  const base = path.join(process.env.LOCALAPPDATA || '', 'NAJD AGENT', 'runtime')
  const name = fs.existsSync(base) ? fs.readdirSync(base).find(entry => entry.startsWith('engine-') && fs.existsSync(path.join(base, entry, 'najd-core.json'))) : null
  if (!name) throw new Error('The managed engine is not prepared on this machine; pass --engine <folder>.')
  return path.join(base, name)
}

async function main() {
  const args = process.argv.slice(2)
  const engine = findEngine(args.includes('--engine') ? args[args.indexOf('--engine') + 1] : null)
  const receipt = JSON.parse(fs.readFileSync(path.join(engine, 'najd-core.json'), 'utf8'))
  const python = path.resolve(engine, receipt.python)
  const uvFolder = fs.readdirSync(path.join(engine, 'tools')).find(name => name.startsWith('uv-'))
  if (!uvFolder) throw new Error('The engine has no uv.')
  const uv = path.join(engine, 'tools', uvFolder, 'uv.exe')
  const version = execFileSync(python, ['-I', '-c', 'import sys; print(".".join(map(str, sys.version_info[:3])))'], { encoding: 'utf8' }).trim()
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'najd-office-lock-'))
  try {
    fs.writeFileSync(path.join(work, 'in.txt'), REQUESTED.join('\n') + '\n')
    const resolved = execFileSync(uv, ['pip', 'compile', path.join(work, 'in.txt'), '--only-binary', ':all:',
      '--python', python, '--python-platform', 'x86_64-pc-windows-msvc', '--no-config', '--no-header', '--no-annotate', '--index-url', 'https://pypi.org/simple'],
    { encoding: 'utf8', env: { ...process.env, UV_CACHE_DIR: path.join(work, 'cache') } })
    const pins = resolved.split(/\r?\n/).map(line => line.trim()).filter(line => line && !line.startsWith('#')).map(line => {
      const match = /^([A-Za-z0-9._-]+)==([A-Za-z0-9.+!-]+)$/.exec(line)
      if (!match) throw new Error('Unpinned resolution line: ' + line)
      return { name: normal(match[1]), version: match[2] }
    })
    const pack = pins
    const lines = []
    for (const pin of pack.sort((a, b) => a.name.localeCompare(b.name))) {
      const response = await fetch(`https://pypi.org/pypi/${encodeURIComponent(pin.name)}/${encodeURIComponent(pin.version)}/json`)
      if (!response.ok) throw new Error(`PyPI has no ${pin.name} ${pin.version}`)
      const data = await response.json()
      const hashes = (data.urls || []).filter(file => file.packagetype === 'bdist_wheel' && installable(file.filename) && /^[a-f0-9]{64}$/.test(file.digests?.sha256 || ''))
        .map(file => file.digests.sha256).sort()
      if (!hashes.length) throw new Error(`${pin.name} ${pin.version} has no wheel for the engine`)
      lines.push(`${pin.name}==${pin.version} ` + hashes.map(hash => '--hash=sha256:' + hash).join(' '))
    }
    const header = [
      '# NAJD Office and design pack (docs/AGENT-PLATFORM-M3-PLAN.md). Generated by scripts/lock-office-pack.cjs; review changes like code.',
      `# engine-python: ${receipt.python.replace(/\\/g, '/')}`,
      `# engine-version: ${version}`,
      `# imports: ${IMPORTS.join(' ')}`
    ]
    const text = [...header, ...lines].join('\n') + '\n'
    if (args.includes('--check')) {
      const current = fs.existsSync(LOCK) ? fs.readFileSync(LOCK, 'utf8').replace(/\r\n/g, '\n') : ''
      if (current !== text) { console.error('office-pack.lock.txt differs from a fresh resolution.'); process.exitCode = 1; return }
      console.log('office-pack.lock.txt matches a fresh resolution.')
      return
    }
    fs.mkdirSync(path.dirname(LOCK), { recursive: true })
    fs.writeFileSync(LOCK, text)
    console.log(`Wrote ${path.relative(process.cwd(), LOCK)}: ${pack.length} packages, sha256 ${createHash('sha256').update(text).digest('hex')}`)
  } finally { fs.rmSync(work, { recursive: true, force: true }) }
}

main().catch(error => { console.error(error.message); process.exit(1) })
